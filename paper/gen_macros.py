#!/usr/bin/env python3
"""Writes results_macros.tex: every number quoted in the paper, computed from the benchmark JSON.

Usage: python3 gen_macros.py [results_dir]
Keeping numbers in generated macros guarantees that the text, the tables and the raw data agree.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "bench", "results")
trust = json.load(open(os.path.join(RES, "trust.json")))
net = json.load(open(os.path.join(RES, "net-all.json")))
micro = json.load(open(os.path.join(RES, "micro.json")))

NUM = {2: "Two", 3: "Three", 4: "Four", 6: "Six", 8: "Eight", 12: "Twelve", 16: "Sixteen", 32: "ThirtyTwo", 64: "SixtyFour"}
LOSS = {0: "Zero", 1: "One", 3: "Three"}
out = ["% AUTO-GENERATED by gen_macros.py from the benchmark results -- do not edit by hand."]


def m(name, value):
    out.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def f(x, d=1):
    return f"{x:.{d}f}"


# ---- trust ----
for key, v in trust["enroll"].items():
    topo, n = key.split(":")
    T = "Mesh" if topo == "mesh" else "Chain"
    s = v["links"] if v["links"] else v["view"]
    m(f"Enr{T}{NUM[int(n)]}", f(s["p50"], 1))
    m(f"Enr{T}{NUM[int(n)]}Pnf", f(s["p95"], 1))
    m(f"Sync{T}{NUM[int(n)]}", f(v["syncMsgs"]["mean"], 0))
    m(f"SyncKiB{T}{NUM[int(n)]}", f(v["syncBytes"]["mean"] / 1024, 0))
for key, v in trust["revoke"].items():
    topo, n = key.split(":")
    T = "Mesh" if topo == "mesh" else "Chain"
    m(f"Rev{T}{NUM[int(n)]}", f(v["revoke"]["p50"], 1))
    m(f"Rev{T}{NUM[int(n)]}Pnf", f(v["revoke"]["p95"], 1))
    m(f"RevMsgs{T}{NUM[int(n)]}", f(v["removeMsgs"]["mean"], 0))
m("AllDigestsAgree", "all" if all(v["hashesAgree"] for v in trust["enroll"].values()) else "not all")
rows = []
for n, v in sorted(trust["antiEntropy"].items(), key=lambda kv: int(kv[0])):
    cur, fix = v["current"], v["fixed"]
    mbps = cur["syncBytesPerCycle"] * 8 / 2.0 / 1e6  # one cycle per 2 s heartbeat interval
    rows.append(f"{n} & {cur['syncMsgsPerCycle']:.0f} & {cur['syncBytesPerCycle'] / 1024:.0f} & {mbps:.2f} & {fix['syncMsgsPerCycle']:.0f} \\\\")
    m(f"AEMsgs{NUM[int(n)]}", f(cur["syncMsgsPerCycle"], 0))
    m(f"AEMiB{NUM[int(n)]}", f(cur["syncBytesPerCycle"] / 2**20, 1))
    m(f"AEMbps{NUM[int(n)]}", f(mbps, 1))
m("AETableRows", "\n".join(rows))

# ---- bulk ----
names = {"unshaped": "Loopback, unshaped", "wifi-300": "300\\,Mb/s, 2\\,ms", "wifi-100-lossy": "100\\,Mb/s, 0.5\\,\\% loss"}
brows = []


def g(x):
    return f"{x:.0f}" if x >= 100 else f"{x:.1f}"


for c in ["unshaped", "wifi-300", "wifi-100-lossy"]:
    b = net["bulk"][c]
    brows.append(f"{names[c]} & {g(b['raw']['mbps']['mean'])} & {g(b['link']['mbps']['mean'])} & {g(b['mux']['mbps']['mean'])}"
                 f" & {b['link']['cpuSecPerGiB']['mean']:.1f} & {b['mux']['cpuSecPerGiB']['mean']:.1f} \\\\")
m("BulkTableRows", "\n".join(brows))
B = net["bulk"]
m("LinkUnshapedGbps", f(B["unshaped"]["link"]["mbps"]["mean"] / 1000, 2))
m("MuxUnshapedGbps", f(B["unshaped"]["mux"]["mbps"]["mean"] / 1000, 2))
m("UnshapedSpeedup", f(B["unshaped"]["link"]["mbps"]["mean"] / B["unshaped"]["mux"]["mbps"]["mean"], 1))
m("CpuRatioUnshaped", f(B["unshaped"]["mux"]["cpuSecPerGiB"]["mean"] / B["unshaped"]["link"]["cpuSecPerGiB"]["mean"], 1))
m("CpuRatioWifi", f(B["wifi-300"]["mux"]["cpuSecPerGiB"]["mean"] / B["wifi-300"]["link"]["cpuSecPerGiB"]["mean"], 1))
m("LinkWifiMbps", f(B["wifi-300"]["link"]["mbps"]["mean"], 1))
m("RawWifiMbps", f(B["wifi-300"]["raw"]["mbps"]["mean"], 1))
m("MuxWifiMbps", f(B["wifi-300"]["mux"]["mbps"]["mean"], 1))
m("MuxWifiLossPct", f(100 * (1 - B["wifi-300"]["mux"]["mbps"]["mean"] / B["wifi-300"]["link"]["mbps"]["mean"]), 1))
m("LinkLossyMbps", f(B["wifi-100-lossy"]["link"]["mbps"]["mean"], 1))
m("MuxLossyMbps", f(B["wifi-100-lossy"]["mux"]["mbps"]["mean"], 1))
m("RawLossyMbps", f(B["wifi-100-lossy"]["raw"]["mbps"]["mean"], 1))

# ---- input latency ----
for r in net["input"]:
    M = {"udp": "Udp", "tcp": "Tcp", "mux": "Mux"}[r["method"]]
    L = LOSS[r["lossPct"]]
    s = r["stats"]
    m(f"Inp{M}{L}Pfifty", f(s["p50"], 1))
    m(f"Inp{M}{L}Pnn", f(s["p99"], 1))
    m(f"Inp{M}{L}Max", f(s["max"], 1))
    m(f"Inp{M}{L}Del", f(100 * r["delivery"], 1))
    m(f"Inp{M}{L}Bulk", f(r["bulkMbps"], 0))
    m(f"Inp{M}{L}Events", str(r["sent"]))

# ---- micro ----
for n, v in micro["poolHash"].items():
    m(f"PoolHash{NUM[int(n)]}", f(v["p50"], 0))
o = micro["other"]
m("SasUs", f(o["sas"]["p50"], 1))
m("FpUs", f(o["fingerprint"]["p50"], 1))
m("GcmOpusUs", f(o["gcmOpus160"]["p50"], 1))
m("GcmPcmUs", f(o["gcmPcm1280"]["p50"], 1))
if "opusEncDec10ms" in o:
    m("OpusUs", f(o["opusEncDec10ms"]["p50"], 0))
    m("OpusBudgetPct", f(100 * (o["opusEncDec10ms"]["p50"] + o["gcmOpus160"]["p50"]) / 10000, 2))
    m("OpusFrameBytes", str(o["opusFrameBytes"]))

open(os.path.join(HERE, "results_macros.tex"), "w").write("\n".join(out) + "\n")
print(f"wrote {len(out) - 1} macros to results_macros.tex")
