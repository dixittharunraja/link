// Generates the Web Portal page the PHONE serves (LinkWebPage.java) from the desktop's page, so the two look
// the same: same markup, same CSS. Only the script differs (the phone speaks plain HTTP, the desktop a WebSocket).
//
//   src-tauri/resources/portal-web.html        the desktop page (source of the look)
//   src-tauri/resources/portal-web-phone.js    the phone page's script
//   -> src-tauri/android/java/in/rodix/link/LinkWebPage.java
//
// Run `npm run gen:phone-portal` after changing either input. It stops with an error when the desktop page no
// longer contains a piece this script patches, rather than writing a half-matching page.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const htmlPath = join(root, 'src-tauri/resources/portal-web.html');
const scriptPath = join(root, 'src-tauri/resources/portal-web-phone.js');
const outPath = join(root, 'src-tauri/android/java/in/rodix/link/LinkWebPage.java');

let html = readFileSync(htmlPath, 'utf8').replace(/\r\n/g, '\n');
const script = readFileSync(scriptPath, 'utf8').replace(/\r\n/g, '\n');

function patch(from, to) {
  if (html.split(from).length !== 2) throw new Error(`portal-web.html no longer has exactly one: ${from.slice(0, 70)}`);
  html = html.replace(from, () => to);
}

patch('<div class="status-msg">Waiting for host to accept connection...</div>', '<div class="status-msg" id="pin-status">Waiting for host to accept connection...</div>');
patch('<div class="downloads-title">Files available from host</div>', '<div class="downloads-title" id="downloads-title">Files available from host</div>');
patch('<title>Link Web Portal</title>', '<title>Link Web Portal</title>');

// Swap the desktop script for the phone's.
const start = html.lastIndexOf('<script>');
const end = html.lastIndexOf('</script>');
if (start < 0 || end < start) throw new Error('portal-web.html has no <script> block');
html = html.slice(0, start) + '<script>\n' + script + '</script>' + html.slice(end + '</script>'.length);

// The external fonts only help when the browser has internet; the page works the same without them.
const lines = html.split('\n');
const literal = lines
  .map((line, i) => '            + "' + line.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + (i < lines.length - 1 ? '\\n"' : '"'))
  .join('\n')
  .replace(/^            \+ /, '');
const bytes = Buffer.byteLength(html, 'utf8');
if (bytes > 60000) throw new Error(`The page is ${bytes} bytes; a Java string constant is limited to 65535`);

writeFileSync(
  outPath,
  `package in.rodix.link;

// GENERATED by scripts/gen-phone-portal-page.mjs from src-tauri/resources/portal-web.html (the desktop's Web Portal
// page) and portal-web-phone.js. Do not edit by hand: change those and run \`npm run gen:phone-portal\`.
final class LinkWebPage {
    private LinkWebPage() {
    }

    static final String PAGE = ${literal};
}
`,
);
console.log(`Wrote ${outPath} (${bytes} bytes)`);
